package net.hulan.ivr.render;

import com.mojang.blaze3d.vertex.PoseStack;
import mtr.mappings.UtilitiesClient;
import net.hulan.ivr.render_promotion.cache.VertexMesh;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.texture.TextureAtlas;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.resources.ResourceLocation;

import java.util.ArrayList;
import java.util.List;

/**
 * Baked, atlas-resolved geometry for the three rotating ticket-barrier arms.
 * <p>
 * The only thing that changes between frames is the rotation angle, and the three arms are the same
 * cuboid copied by the exact 120-degree symmetry of the shared axis. The whole assembly is therefore a
 * constant in block space, and the only input that can change is the block atlas. The mesh is built
 * once after every resource reload ({@link #rebuild()} is driven by the model-manager hook) and the
 * renderer replays it with a single pose rotation per frame instead of rebuilding quads and looking up
 * the sprite every frame.
 */
public final class TicketBarrierMesh {

    private static final ResourceLocation POLE_TEXTURE = new ResourceLocation("ivr", "block/metalic_v2_031");
    private static final float PIVOT_X = 12.0F / 16.0F;
    private static final float PIVOT_Y = 10.5F / 16.0F;
    private static final float PIVOT_Z = 8.0F / 16.0F;
    // Mirror the axis tilt so the two rotated arms point downward from the machine-side pivot.
    private static final float AXIS_AZIMUTH = 35.264F;

    // The unrotated arm is the seed geometry. The other two arms are generated by the exact
    // 120-degree symmetry of the common axis.
    private static final float ARM_FROM_X = 2.0F / 16.0F;
    private static final float ARM_FROM_Y = 10.0F / 16.0F;
    private static final float ARM_FROM_Z = 7.5F / 16.0F;
    private static final float ARM_TO_X = 12.0F / 16.0F;
    private static final float ARM_TO_Y = 11.0F / 16.0F;
    private static final float ARM_TO_Z = 8.5F / 16.0F;

    private static final int WHITE = 0xFFFFFFFF;
    private static final float[][] ARM_MATRICES = {armMatrix(0.0F), armMatrix(120.0F), armMatrix(240.0F)};

    private static volatile VertexMesh mesh;

    private TicketBarrierMesh() {
    }

    /**
     * Returns the baked mesh, rebuilding it if the reload hook has not produced one yet (for example
     * when the model-manager injection is unavailable on this version). The normal path never rebuilds.
     */
    public static VertexMesh get() {
        VertexMesh current = mesh;
        return current != null ? current : rebuild();
    }

    /** Re-bakes the arms against the current block atlas. Idempotent and safe to call on every reload. */
    public static synchronized VertexMesh rebuild() {
        Minecraft minecraft = Minecraft.getInstance();
        TextureAtlasSprite sprite;
        try {
            sprite = minecraft.getTextureAtlas(TextureAtlas.LOCATION_BLOCKS).apply(POLE_TEXTURE);
        } catch (RuntimeException exception) {
            // The atlas is not stitched yet; keep the previous mesh so rendering never breaks.
            return mesh;
        }
        if (sprite == null) {
            return mesh;
        }
        VertexMesh rebuilt = new VertexMesh(build(sprite));
        mesh = rebuilt;
        return rebuilt;
    }

    /**
     * Applies the shared arm-axis rotation around the machine-side pivot. The baked arms already carry
     * their own 0/120/240 offsets, so one call rotates the whole assembly.
     */
    public static void rotateAroundAxis(PoseStack matrices, float angle) {
        matrices.translate(PIVOT_X, PIVOT_Y, PIVOT_Z);
        UtilitiesClient.rotateZDegrees(matrices, AXIS_AZIMUTH);
        UtilitiesClient.rotateYDegrees(matrices, 90.0F);
        UtilitiesClient.rotateZDegrees(matrices, angle);
        UtilitiesClient.rotateYDegrees(matrices, -90.0F);
        UtilitiesClient.rotateZDegrees(matrices, -AXIS_AZIMUTH);
        matrices.translate(-PIVOT_X, -PIVOT_Y, -PIVOT_Z);
    }

    private static List<VertexMesh.Vertex> build(TextureAtlasSprite sprite) {
        float u0 = sprite.getU(0.0F);
        float u1 = sprite.getU(16.0F);
        float v0 = sprite.getV(0.0F);
        float v1 = sprite.getV(16.0F);
        List<VertexMesh.Vertex> vertices = new ArrayList<>(72);
        for (float[] matrix : ARM_MATRICES) {
            // -Z, +X, +Z, -X, +Y, -Y: same faces, winding and UVs as the original immediate emission.
            face(vertices, matrix, u0, v0, u1, v1, 0.0F, 0.0F, -1.0F,
                    ARM_FROM_X, ARM_FROM_Y, ARM_FROM_Z,
                    ARM_FROM_X, ARM_TO_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_FROM_Y, ARM_FROM_Z);
            face(vertices, matrix, u0, v0, u1, v1, 1.0F, 0.0F, 0.0F,
                    ARM_TO_X, ARM_FROM_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_TO_Z,
                    ARM_TO_X, ARM_FROM_Y, ARM_TO_Z);
            face(vertices, matrix, u0, v0, u1, v1, 0.0F, 0.0F, 1.0F,
                    ARM_FROM_X, ARM_FROM_Y, ARM_TO_Z,
                    ARM_TO_X, ARM_FROM_Y, ARM_TO_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_TO_Z,
                    ARM_FROM_X, ARM_TO_Y, ARM_TO_Z);
            face(vertices, matrix, u0, v0, u1, v1, -1.0F, 0.0F, 0.0F,
                    ARM_FROM_X, ARM_FROM_Y, ARM_FROM_Z,
                    ARM_FROM_X, ARM_FROM_Y, ARM_TO_Z,
                    ARM_FROM_X, ARM_TO_Y, ARM_TO_Z,
                    ARM_FROM_X, ARM_TO_Y, ARM_FROM_Z);
            face(vertices, matrix, u0, v0, u1, v1, 0.0F, 1.0F, 0.0F,
                    ARM_FROM_X, ARM_TO_Y, ARM_FROM_Z,
                    ARM_FROM_X, ARM_TO_Y, ARM_TO_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_TO_Z,
                    ARM_TO_X, ARM_TO_Y, ARM_FROM_Z);
            face(vertices, matrix, u0, v0, u1, v1, 0.0F, -1.0F, 0.0F,
                    ARM_FROM_X, ARM_FROM_Y, ARM_TO_Z,
                    ARM_FROM_X, ARM_FROM_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_FROM_Y, ARM_FROM_Z,
                    ARM_TO_X, ARM_FROM_Y, ARM_TO_Z);
        }
        return vertices;
    }

    private static void face(List<VertexMesh.Vertex> vertices, float[] matrix,
                             float u0, float v0, float u1, float v1,
                             float normalX, float normalY, float normalZ,
                             float x0, float y0, float z0,
                             float x1, float y1, float z1,
                             float x2, float y2, float z2,
                             float x3, float y3, float z3) {
        float[] normal = rotateNormal(matrix, normalX, normalY, normalZ);
        vertex(vertices, matrix, normal, u0, v0, x0, y0, z0);
        vertex(vertices, matrix, normal, u0, v1, x1, y1, z1);
        vertex(vertices, matrix, normal, u1, v1, x2, y2, z2);
        vertex(vertices, matrix, normal, u1, v0, x3, y3, z3);
    }

    private static void vertex(List<VertexMesh.Vertex> vertices, float[] matrix, float[] normal,
                               float u, float v, float x, float y, float z) {
        float dx = x - PIVOT_X;
        float dy = y - PIVOT_Y;
        float dz = z - PIVOT_Z;
        vertices.add(new VertexMesh.Vertex(
                PIVOT_X + matrix[0] * dx + matrix[1] * dy + matrix[2] * dz,
                PIVOT_Y + matrix[3] * dx + matrix[4] * dy + matrix[5] * dz,
                PIVOT_Z + matrix[6] * dx + matrix[7] * dy + matrix[8] * dz,
                u, v, normal[0], normal[1], normal[2], WHITE));
    }

    private static float[] rotateNormal(float[] matrix, float x, float y, float z) {
        float rotatedX = matrix[0] * x + matrix[1] * y + matrix[2] * z;
        float rotatedY = matrix[3] * x + matrix[4] * y + matrix[5] * z;
        float rotatedZ = matrix[6] * x + matrix[7] * y + matrix[8] * z;
        float length = (float) Math.sqrt(rotatedX * rotatedX + rotatedY * rotatedY + rotatedZ * rotatedZ);
        if (length < 1.0E-6F) {
            return new float[]{0.0F, 0.0F, 1.0F};
        }
        return new float[]{rotatedX / length, rotatedY / length, rotatedZ / length};
    }

    /**
     * Same composition as {@code rotateAroundAxis(matrices, angle)} but evaluated as pure math, so the
     * bake does not depend on any version-specific matrix type. Verified against JOML, which is what
     * {@code PoseStack} uses internally.
     */
    private static float[] armMatrix(float angle) {
        float[] matrix = rotationZ(AXIS_AZIMUTH);
        matrix = multiply(matrix, rotationY(90.0F));
        matrix = multiply(matrix, rotationZ(angle));
        matrix = multiply(matrix, rotationY(-90.0F));
        return multiply(matrix, rotationZ(-AXIS_AZIMUTH));
    }

    private static float[] rotationZ(float degrees) {
        double radians = Math.toRadians(degrees);
        float cos = (float) Math.cos(radians);
        float sin = (float) Math.sin(radians);
        return new float[]{cos, -sin, 0.0F, sin, cos, 0.0F, 0.0F, 0.0F, 1.0F};
    }

    private static float[] rotationY(float degrees) {
        double radians = Math.toRadians(degrees);
        float cos = (float) Math.cos(radians);
        float sin = (float) Math.sin(radians);
        return new float[]{cos, 0.0F, sin, 0.0F, 1.0F, 0.0F, -sin, 0.0F, cos};
    }

    private static float[] multiply(float[] a, float[] b) {
        float[] result = new float[9];
        for (int row = 0; row < 3; row++) {
            for (int column = 0; column < 3; column++) {
                float sum = 0.0F;
                for (int k = 0; k < 3; k++) {
                    sum += a[row * 3 + k] * b[k * 3 + column];
                }
                result[row * 3 + column] = sum;
            }
        }
        return result;
    }
}
